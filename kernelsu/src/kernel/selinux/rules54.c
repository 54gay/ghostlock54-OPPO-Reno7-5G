/*
 * 5.4 policy loader: applies KernelSU rule sets on this vendor 5.4 kernel.
 *
 * The upstream (5.7+) implementation swaps selinux_state.policy directly and
 * depends on the split selinux_policy structure, which 5.4 does not have.
 * On 5.4 the supported path is:
 *   security_read_policy() -> policydb_read() -> apply ksu rules
 *   -> policydb_write() -> security_load_policy()
 * security_load_policy() performs the proper sidtab conversion, swap and
 * AVC/policy-load notifications, so nothing internal needs to be patched.
 */
#include <linux/errno.h>
#include <linux/kernel.h>
#include <linux/mutex.h>
#include <linux/printk.h>
#include <linux/slab.h>
#include <linux/string.h>
#include <linux/uaccess.h>
#include <linux/vmalloc.h>

#include "uapi/selinux.h"
#include "klog.h" // IWYU pragma: keep
#include "selinux.h"
